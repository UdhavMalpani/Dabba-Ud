"""
Single-duct trial analyzer (branch pre-component-test).

Reads the hand-logged CSV from the kitchen-scale rig (cad/test_rig.scad) with three configs
    open_*            open prop (arm on the 40 mm riser, no duct)
    duct_*            duct, no grilles
    duct_*_grilles    duct + inlet and exit grilles
and measures what the whole design rests on: the enclosure power penalty, assumed +20 %.

Per config it fits momentum-theory scaling T = k * P^(2/3) (T thrust, P electrical power), so
    thrust ratio at equal power       = k_cfg / k_open
    power penalty at equal thrust     = (k_open / k_cfg)^(3/2) - 1       (design assumption 0.20)
    figure of merit (open prop)       FM = T^1.5 / sqrt(2 rho A) / (eta * P)   (design assumption 0.60)
If no current was logged it falls back to comparing thrust at equal throttle (weaker: a duct
changes motor loading).

    python src/analysis/single_duct_trial_analyzer.py --csv data/my_trial.csv
    python src/analysis/single_duct_trial_analyzer.py --demo        # SYNTHETIC example data

Outputs: outputs/test_rig/single_duct_trial_results.json, outputs/plots/fig10_single_duct_trial.png
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path
from typing import Dict, List

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "outputs" / "test_rig"
PLOT = ROOT / "outputs" / "plots" / "fig10_single_duct_trial.png"
MEAS = ROOT / "config" / "test_rig_measurements.json"

RHO_HYD = 1.09                 # kg/m^3, IIIT Hyderabad 540 m ASL, 30 C
ETA_MOTOR = 0.80               # motor+ESC efficiency (same as sizing model)
DESIGN_PENALTY = 0.20          # +20 % enclosure power assumption
DESIGN_FM = 0.60
G = 9.81


def read_trial(paths: List[Path]) -> Dict[str, Dict[str, np.ndarray]]:
    rows: Dict[str, List[Dict[str, float]]] = {}
    for p in paths:
        lines = [ln for ln in p.read_text().splitlines() if ln.strip() and not ln.lstrip().startswith("#")]
        for r in csv.DictReader(lines):
            num = {}
            for k in ("throttle_pct", "thrust_g", "voltage_v", "current_a", "power_w", "rpm"):
                v = (r.get(k) or "").strip()
                num[k] = float(v) if v else float("nan")
            if not math.isfinite(num["power_w"]) and math.isfinite(num["voltage_v"]) and math.isfinite(num["current_a"]):
                num["power_w"] = num["voltage_v"] * num["current_a"]
            rows.setdefault(r["config"].strip(), []).append(num)
    return {c: {k: np.array([x[k] for x in v]) for k in v[0]} for c, v in rows.items()}


def kind(cfg: str) -> str:
    c = cfg.lower()
    return "open" if c.startswith("open") else ("duct_grilles" if "grille" in c else "duct")


def fit_k(p_w: np.ndarray, t_g: np.ndarray) -> float:
    """Least squares on T = k P^(2/3) through the origin."""
    ok = np.isfinite(p_w) & np.isfinite(t_g) & (p_w > 2) & (t_g > 10)
    x = p_w[ok] ** (2 / 3)
    return float(np.sum(x * t_g[ok]) / np.sum(x * x)) if ok.sum() >= 2 else float("nan")


def demo_csv(path: Path) -> None:
    """SYNTHETIC: open-prop FM 0.55, duct +6 % thrust at equal power, grilles -12 % vs open."""
    rng = np.random.default_rng(3)
    lines = ["# SYNTHETIC demo data - generated by --demo, not a measurement",
             "config,tip_gap_mm,pwm_us,throttle_pct,thrust_g,voltage_v,current_a,power_w,rpm"]
    area = math.pi * 0.1302 ** 2 / 4
    for cfg, gap, mult in (("open_5in_3blade", "", 1.00), ("duct_5in_gap1.5", "1.5", 1.06),
                           ("duct_5in_gap1.5_grilles", "1.5", 0.88)):
        for thr in (20, 30, 40, 50, 60, 70):
            p = 140 * (thr / 70) ** 2.6
            t_n = (0.55 * ETA_MOTOR * p * math.sqrt(2 * RHO_HYD * area)) ** (2 / 3) * mult
            v = 15.6 - 0.02 * p / 15.6
            t_g = t_n / G * 1000 * (1 + rng.normal(0, 0.015))
            lines.append(f"{cfg},{gap},{1000 + 10 * thr},{thr},{t_g:.0f},{v:.2f},{p / v:.2f},{p:.1f},0")
    path.write_text("\n".join(lines) + "\n")


def main(argv=None) -> Dict:
    ap = argparse.ArgumentParser(description="Single-duct trial analyzer")
    ap.add_argument("--csv", action="append", help="hand-logged trial CSV (repeatable)")
    ap.add_argument("--demo", action="store_true", help="analyse SYNTHETIC example data")
    ap.add_argument("--prop-d", type=float, default=None, help="prop diameter mm (default: measurements JSON)")
    ap.add_argument("--rho", type=float, default=RHO_HYD, help="air density during the test (kg/m^3)")
    args = ap.parse_args(argv)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    if args.demo:
        demo = OUT_DIR / "single_duct_trial_DEMO_synthetic.csv"
        demo_csv(demo)
        paths = [demo]
    elif args.csv:
        paths = [Path(c) for c in args.csv]
    else:
        ap.error("give --csv <file> (template: data/single_duct_trial_template.csv) or --demo")

    prop_d = args.prop_d or json.loads(MEAS.read_text()).get("prop_diameter_mm") or 127.0
    area = math.pi * (prop_d / 1000) ** 2 / 4
    data = read_trial(paths)
    have_power = all(np.isfinite(d["power_w"]).sum() >= 2 for d in data.values())

    res = {"source": [str(p) for p in paths], "synthetic": bool(args.demo), "prop_d_mm": prop_d,
           "rho": args.rho, "basis": "equal electrical power" if have_power else "equal throttle (no current logged)",
           "configs": {}}
    open_cfg = next((c for c in data if kind(c) == "open"), None)
    for cfg, d in data.items():
        r = {"kind": kind(cfg), "points": int(len(d["thrust_g"])), "max_thrust_g": float(np.nanmax(d["thrust_g"]))}
        if have_power:
            r["k_g_per_W23"] = fit_k(d["power_w"], d["thrust_g"])
            t_n, p = d["thrust_g"] * G / 1000, d["power_w"]
            ok = (p > 2) & (t_n > 0.1)
            fm = t_n[ok] ** 1.5 / math.sqrt(2 * args.rho * area) / (ETA_MOTOR * p[ok])
            r["fm_disc_mean"] = float(np.mean(fm)) if ok.any() else float("nan")
            r["g_per_W_at_max"] = float(d["thrust_g"][np.nanargmax(d["thrust_g"])] / p[np.nanargmax(d["thrust_g"])])
        res["configs"][cfg] = r

    if open_cfg:
        ref = res["configs"][open_cfg]
        for cfg, r in res["configs"].items():
            if cfg == open_cfg:
                continue
            if have_power:
                ratio = r["k_g_per_W23"] / ref["k_g_per_W23"]
                r["thrust_ratio_vs_open_equal_power"] = round(ratio, 3)
                r["power_penalty_vs_open_equal_thrust"] = round(ratio ** -1.5 - 1, 3)
            else:
                a, b = data[open_cfg], data[cfg]
                common = np.intersect1d(a["throttle_pct"], b["throttle_pct"])
                ra = [b["thrust_g"][b["throttle_pct"] == t][0] / a["thrust_g"][a["throttle_pct"] == t][0]
                      for t in common if t >= 30]
                r["thrust_ratio_vs_open_equal_throttle"] = round(float(np.mean(ra)), 3) if ra else None

    full = next((r for r in res["configs"].values() if r["kind"] == "duct_grilles"), None)
    if full and "power_penalty_vs_open_equal_thrust" in full:
        pen = full["power_penalty_vs_open_equal_thrust"]
        res["verdict"] = (f"Measured enclosure power penalty {pen * 100:+.1f} % vs design assumption "
                          f"+{DESIGN_PENALTY * 100:.0f} %: "
                          + ("within assumption - the +20 % sizing case is conservative" if pen <= DESIGN_PENALTY
                             else "WORSE than assumed - re-run sizing with this penalty"))
    (OUT_DIR / "single_duct_trial_results.json").write_text(json.dumps(res, indent=2, default=float))

    # ---- figure ----
    fig, ax = plt.subplots(1, 2, figsize=(12, 4.6))
    colors = {"open": "#475569", "duct": "#0f766e", "duct_grilles": "#c2410c"}
    for cfg, d in data.items():
        c = colors[kind(cfg)]
        x = d["power_w"] if have_power else d["throttle_pct"]
        ax[0].plot(x, d["thrust_g"], "o", color=c, label=cfg)
        k = res["configs"][cfg].get("k_g_per_W23")
        if k and math.isfinite(k):
            xx = np.linspace(0, np.nanmax(x), 60)
            ax[0].plot(xx, k * xx ** (2 / 3), "-", color=c, lw=1.2)
    ax[0].set_xlabel("Electrical power (W)" if have_power else "Throttle (%)")
    ax[0].set_ylabel("Thrust (g)")
    ax[0].set_title("Thrust vs " + ("power, fits T = k P^(2/3)" if have_power else "throttle"))
    ax[0].grid(alpha=0.3)
    ax[0].legend(fontsize=8)
    names = [c for c, r in res["configs"].items() if "power_penalty_vs_open_equal_thrust" in r]
    if names:
        vals = [100 * res["configs"][c]["power_penalty_vs_open_equal_thrust"] for c in names]
        ax[1].bar(names, vals, color=[colors[kind(c)] for c in names])
        ax[1].axhline(100 * DESIGN_PENALTY, color="k", ls="--", lw=1, label="design assumption +20 %")
        ax[1].axhline(0, color="k", lw=0.6)
        for i, v in enumerate(vals):
            ax[1].text(i, v + (1 if v >= 0 else -3), f"{v:+.1f} %", ha="center", fontsize=9)
        ax[1].set_ylabel("Extra power for the same thrust vs open prop (%)")
        ax[1].legend(fontsize=8)
    else:
        ax[1].text(0.5, 0.5, "Log current (watt meter) to get\nthe power penalty", ha="center", va="center")
    ax[1].set_title("Enclosure power penalty")
    ax[1].grid(alpha=0.3, axis="y")
    fig.suptitle(f"Single-duct trial, prop {prop_d:.1f} mm" + ("  (SYNTHETIC DEMO DATA)" if args.demo else ""),
                 color="#b91c1c" if args.demo else "black")
    fig.tight_layout()
    PLOT.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(PLOT, dpi=150)

    print(f"Basis: {res['basis']}   prop {prop_d:.1f} mm   rho {args.rho}")
    for cfg, r in res["configs"].items():
        extra = ""
        if "power_penalty_vs_open_equal_thrust" in r:
            extra = (f"  thrust x{r['thrust_ratio_vs_open_equal_power']:.3f} at equal power, "
                     f"power {r['power_penalty_vs_open_equal_thrust'] * 100:+.1f} % at equal thrust")
        elif r.get("thrust_ratio_vs_open_equal_throttle"):
            extra = f"  thrust x{r['thrust_ratio_vs_open_equal_throttle']:.3f} at equal throttle"
        fm = f"  FM {r['fm_disc_mean']:.2f}" if "fm_disc_mean" in r else ""
        print(f"  {cfg:<28} max {r['max_thrust_g']:.0f} g{fm}{extra}")
    if "verdict" in res:
        print(res["verdict"])
    print(f"Saved {OUT_DIR / 'single_duct_trial_results.json'} and {PLOT}")
    return res


if __name__ == "__main__":
    main()
