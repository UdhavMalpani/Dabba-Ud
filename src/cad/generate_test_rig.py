"""
Pre-component single-duct thrust rig generator (branch pre-component-test).

Reads caliper values from config/test_rig_measurements.json and writes, to outputs/test_rig/:
    duct_test_rig.stl        duct ring sized to the measured prop (same geometry code as the
                             flight ducts in generate_cad_stl.py), PETG
    grille_test_rig.stl      matching square grille = EXIT grille (taped on top of the arm), PLA
    test_rig_dims.scad       measured values for cad/test_rig.scad
    fit_band.stl             20-min throat ring: check prop clearance before the full duct
    stand.stl                windowed tube cradle + arm post (inlet held >= 150 mm above the scale)
    motor_arm.stl            arm through the duct exit slot, motor pad at the centre
    open_riser.stl           40 mm riser for the open-prop baseline run
    inlet_grille.stl         grille trimmed round: slides up the stand tube, sits under the ledge
    test_rig_summary.json    derived geometry, checks, print masses, screw list

The rig parts are compiled by OpenSCAD (auto-detected; skipped with a warning if missing).

    python src/cad/generate_test_rig.py [--measurements config/test_rig_measurements.json]
"""

from __future__ import annotations

import argparse
import json
import math
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate_cad_stl as gc  # noqa: E402

OUT_DIR = ROOT / "outputs" / "test_rig"
SCAD = ROOT / "cad" / "test_rig.scad"
DEFAULT_MEAS = ROOT / "config" / "test_rig_measurements.json"

DEFAULTS = {"prop_diameter_mm": 127.0, "tip_gap_mm": 1.5, "motor_base_to_prop_seat_mm": 30.0,
            "prop_hub_thickness_mm": 7.0, "motor_bell_diameter_mm": 34.0,
            "motor_center_clearance_d_mm": 10.0, "inlet_clearance_mm": 150.0}
RIG_PARTS = [("fit_band", "PETG"), ("stand", "PLA"), ("motor_arm", "PETG"), ("open_riser", "PLA"),
             ("inlet_grille", "PLA")]
M3_LENGTHS = (6, 8, 10, 12, 16, 20, 25, 30)

# mirror of cad/test_rig.scad
DUCT_LEN, ROTOR_DEPTH, LIP_R, WALL_T, SLOT_H = 50.0, 15.0, 6.5, 1.6, 12.0
ARM_H, PAD_FLOOR, RISER_H = 12.0, 5.0, 40.0


def load_measurements(path: Path) -> Dict:
    raw = json.loads(path.read_text())
    m, unmeasured = {}, []
    for k, dflt in DEFAULTS.items():
        v = raw.get(k)
        if v is None:
            unmeasured.append(k)
            v = dflt
        m[k] = float(v)
    s = raw.get("motor_bolt_spacing_mm")
    if s is None:
        unmeasured.append("motor_bolt_spacing_mm")
        m["bolt_min"], m["bolt_max"] = 16.0, 19.0
    else:
        m["bolt_min"] = m["bolt_max"] = float(s)
    m["unmeasured"] = unmeasured
    m["raw"] = raw
    return m


def derived(m: Dict) -> Dict:
    d = gc.duct_dims(m["prop_diameter_mm"], m["tip_gap_mm"])
    prop_depth = (DUCT_LEN - ROTOR_DEPTH) + 3.0
    arm_bot_raw = prop_depth - m["motor_base_to_prop_seat_mm"] - m["prop_hub_thickness_mm"] / 2
    arm_bot = min(arm_bot_raw, SLOT_H - 0.5)
    spacer = max(0.0, arm_bot_raw - arm_bot)
    screw_need = PAD_FLOOR + spacer + 3.5                     # <= 4 mm into the motor
    motor_screw = max([L for L in M3_LENGTHS if L <= screw_need] or [M3_LENGTHS[0]])
    return {
        "bore_d_mm": d["bore_d"], "duct_od_mm": d["od"], "exit_d_mm": d["exit_d"],
        "throat_depth_range_mm": [DUCT_LEN - ROTOR_DEPTH, DUCT_LEN - LIP_R],
        "prop_plane_depth_below_exit_mm": prop_depth,
        "arm_underside_depth_below_exit_mm": arm_bot, "motor_spacer_mm": spacer,
        "motor_screw": f"4 x M3x{motor_screw} (into motor {motor_screw - PAD_FLOOR - spacer:.1f} mm; max 4)",
        "post_screws": "2 x M3x20 (arm -> post), self-tap into 2.6 mm pilots",
        "riser_screws": "1 x M3x16 (riser -> post) + the 2 x M3x20 arm screws",
        "inlet_height_above_scale_mm": m["inlet_clearance_mm"],
        "prop_height_above_scale_mm": m["inlet_clearance_mm"] + DUCT_LEN - prop_depth,
    }


def write_scad_include(m: Dict) -> Path:
    p = OUT_DIR / "test_rig_dims.scad"
    p.write_text(
        "// generated by src/cad/generate_test_rig.py from config/test_rig_measurements.json - do not edit\n"
        f"prop_d = {m['prop_diameter_mm']:.3f};\n"
        f"tip_gap = {m['tip_gap_mm']:.3f};\n"
        f"motor_bolt_min = {m['bolt_min']:.3f};\n"
        f"motor_bolt_max = {m['bolt_max']:.3f};\n"
        f"motor_seat_h = {m['motor_base_to_prop_seat_mm']:.3f};\n"
        f"prop_hub_t = {m['prop_hub_thickness_mm']:.3f};\n"
        f"motor_bell_d = {m['motor_bell_diameter_mm']:.3f};\n"
        f"motor_center_d = {m['motor_center_clearance_d_mm']:.3f};\n"
        f"inlet_clear = {m['inlet_clearance_mm']:.3f};\n")
    return p


def find_openscad() -> Optional[str]:
    exe = shutil.which("openscad")
    if exe:
        return exe
    for c in (r"C:\Program Files\OpenSCAD\openscad.exe", r"C:\Program Files (x86)\OpenSCAD\openscad.exe",
              "/usr/bin/openscad", "/Applications/OpenSCAD.app/Contents/MacOS/OpenSCAD"):
        if Path(c).exists():
            return c
    return None


def read_any_stl(path: Path) -> np.ndarray:
    """Triangles (n,3,3) from a binary or ASCII STL (OpenSCAD 2021 writes ASCII)."""
    raw = path.read_bytes()
    if raw[:5] == b"solid" and b"facet" in raw[:400]:
        v = [list(map(float, ln.split()[1:4])) for ln in raw.decode("ascii", "ignore").splitlines()
             if ln.strip().startswith("vertex")]
        return np.asarray(v, float).reshape(-1, 3, 3)
    return gc.read_binary_stl(path)


def stl_report(path: Path, material: str) -> Dict:
    tris = read_any_stl(path)
    chk = gc.check_tris(tris)
    lo, hi = tris.reshape(-1, 3).min(0), tris.reshape(-1, 3).max(0)
    dims = hi - lo
    vol, area = chk["volume_mm3"] / 1000.0, chk["area_mm2"] / 100.0
    m_sliced, _ = gc.sliced_mass_g(vol, area, gc.MATERIALS[material])
    return {"file": str(path.relative_to(ROOT)).replace("\\", "/"), "material": material,
            "triangles": int(len(tris)), "closed_manifold": chk["closed_2manifold"],
            "volume_cm3": round(vol, 2), "mass_est_g": round(m_sliced, 1),
            "bbox_mm": [round(float(x), 1) for x in dims],
            "fits_p1s": bool(np.all(dims <= np.array(gc.BED_MM)))}


def main(argv=None) -> Dict:
    ap = argparse.ArgumentParser(description="Pre-component single-duct thrust rig generator")
    ap.add_argument("--measurements", default=str(DEFAULT_MEAS))
    args = ap.parse_args(argv)

    m = load_measurements(Path(args.measurements))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    geo = derived(m)

    # duct + grille from the flight-part code (generate_cad_stl's grille reads its module prop_d_mm)
    gc.prop_d_mm = m["prop_diameter_mm"]
    parts: List[Dict] = []
    duct_shells, _ = gc.build_duct_ring(m["prop_diameter_mm"], m["tip_gap_mm"])
    for name, shells, mat in (("duct_test_rig", duct_shells, "PETG"),
                              ("grille_test_rig", gc.build_grille(), "PLA")):
        path = OUT_DIR / f"{name}.stl"
        gc.write_binary_stl(path, shells, name)
        parts.append(stl_report(path, mat))

    write_scad_include(m)
    exe = find_openscad()
    scad_ok = exe is not None
    if not exe:
        print("WARNING: OpenSCAD not found - rig parts skipped (install: winget install --id OpenSCAD.OpenSCAD -e)")
    else:
        for part, mat in RIG_PARTS:
            out = OUT_DIR / f"{part}.stl"
            r = subprocess.run([exe, "-o", str(out), "-D", f'part="{part}"', str(SCAD)],
                               capture_output=True, text=True)
            errs = [ln for ln in (r.stdout + r.stderr).splitlines() if "ERROR" in ln]
            if r.returncode != 0 or errs or not out.exists():
                scad_ok = False
                print(f"OpenSCAD failed on {part}:\n" + "\n".join(errs or (r.stdout + r.stderr).splitlines()[-8:]))
                continue
            parts.append(stl_report(out, mat))

    checks = {
        "prop_plane_inside_straight_throat": geo["throat_depth_range_mm"][0] <= geo["prop_plane_depth_below_exit_mm"]
                                             <= geo["throat_depth_range_mm"][1],
        "tip_gap_ge_1mm": m["tip_gap_mm"] >= 1.0,
        "bell_clears_bore": m["motor_bell_diameter_mm"] < geo["bore_d_mm"] - 20,
        "all_parts_closed": all(p["closed_manifold"] for p in parts),
        "all_parts_fit_p1s": all(p["fits_p1s"] for p in parts),
        "openscad_parts_built": scad_ok,
    }
    summary = {"measurements_used": {k: v for k, v in m.items() if k != "raw"},
               "unmeasured_using_defaults": m["unmeasured"], "geometry": geo, "parts": parts, "checks": checks}
    (OUT_DIR / "test_rig_summary.json").write_text(json.dumps(summary, indent=2))

    print(f"\nSingle-duct test rig  (prop {m['prop_diameter_mm']:.1f} mm, tip gap {m['tip_gap_mm']:.2f} mm)")
    print(f"  bore {geo['bore_d_mm']:.1f} mm, duct OD {geo['duct_od_mm']:.1f} mm, prop plane "
          f"{geo['prop_plane_depth_below_exit_mm']:.0f} mm below the exit face, "
          f"{geo['prop_height_above_scale_mm']:.0f} mm above the scale")
    if geo["motor_spacer_mm"] > 0:
        print(f"  short motor: pad drops on a {geo['motor_spacer_mm']:.1f} mm spacer")
    print(f"\n{'Part':<18}{'Mat':>5}{'Mass g':>8}{'Closed':>8}{'Fits':>6}  bbox mm")
    for p in parts:
        print(f"{Path(p['file']).stem:<18}{p['material']:>5}{p['mass_est_g']:>8.1f}{str(p['closed_manifold']):>8}"
              f"{str(p['fits_p1s']):>6}  {' x '.join(f'{x:.1f}' for x in p['bbox_mm'])}")
    print(f"\nScrews: {geo['motor_screw']}; {geo['post_screws']}; {geo['riser_screws']}")
    if m["unmeasured"]:
        print("STILL UNMEASURED (defaults used): " + ", ".join(m["unmeasured"]))
    bad = [k for k, v in checks.items() if not v]
    print("Checks: " + ("all passed" if not bad else "FAILED " + ", ".join(bad)))
    print(f"Saved -> {OUT_DIR}")
    return summary


if __name__ == "__main__":
    main()
